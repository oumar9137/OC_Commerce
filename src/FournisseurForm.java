   public void chargerFournisseurs(){
 try{
 Connection con = ConnexionBD.getConnection();
 String sql = "SELECT * FROM fournisseur";
 java.sql.Statement st = con.createStatement();
 java.sql.ResultSet rs = st.executeQuery(sql);
 
 javax.swing.table.DefaultTableModel model =
(javax.swing.table.DefaultTableModel) tableFournisseur.getModel();
 model.setRowCount(0); // vide l'ancienne liste
 
 // si la table n'a pas de colonnes, on les crée
 if(model.getColumnCount() == 0){
 model.setColumnIdentifiers(new Object[]{"ID", "Nom", "Prenom", "Tel",
"Adresse"});
 }
 while(rs.next()){
 model.addRow(new Object[]{
 rs.getInt("id_fournisseur"),
 rs.getString("nom"),
 rs.getString("prenom"),
 rs.getString("telephone"),
 rs.getString("adresse")
 });
 }
 }catch(Exception e){
 System.out.println(e.getMessage());
 }
}

