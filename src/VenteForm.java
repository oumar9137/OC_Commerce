    private void btnVendreActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnVendreActionPerformed
        String produitSelectionne=(String)comboProduitVente.getSelectedItem();
        String clientSelectionne=(String)comboClient.getSelectedItem();
        int idProduit=lireIdSelection(produitSelectionne), idClient=lireIdSelection(clientSelectionne);
        int idUtilisateur=SessionUtilisateur.getIdUtilisateur();
        final int quantite; final double prixUnitaire;
        try {
            quantite=Integer.parseInt(txtQuantiteVente.getText().trim());
            prixUnitaire=Double.parseDouble(txtPrixVente.getText().trim().replace(',', '.'));
        } catch(NumberFormatException ex) {
            JOptionPane.showMessageDialog(this,"Entrez une quantité entière et un prix valides.");return;
        }
        if(idProduit<1||idClient<1){JOptionPane.showMessageDialog(this,"Choisissez un produit et un client valides.");return;}
        if(quantite<1||!Double.isFinite(prixUnitaire)||prixUnitaire<=0){JOptionPane.showMessageDialog(this,"La quantité et le prix doivent être supérieurs à zéro.");return;}
        if(idUtilisateur<1){JOptionPane.showMessageDialog(this,"Votre session a expiré. Reconnectez-vous.");return;}
        int idVente;
        try (Connection con=ConnexionBD.getConnection()) {
            if(con==null)throw new SQLException("Connexion à la base indisponible.");
            con.setAutoCommit(false);
            try {
                try(PreparedStatement stockQuery=con.prepareStatement("SELECT stock FROM produit WHERE id_produit=? FOR UPDATE")){
                    stockQuery.setInt(1,idProduit);try(ResultSet rs=stockQuery.executeQuery()){
                        if(!rs.next())throw new SQLException("Ce produit n'existe plus.");
                        int stockActuel=rs.getInt(1);if(stockActuel<quantite)throw new SQLException("Stock insuffisant. Stock actuel : "+stockActuel);
                    }
                }
                try(PreparedStatement p=con.prepareStatement("INSERT INTO vente(date_vente,id_client,id_utilisateur) VALUES(NOW(),?,?)",Statement.RETURN_GENERATED_KEYS)){
                    p.setInt(1,idClient);p.setInt(2,idUtilisateur);p.executeUpdate();try(ResultSet keys=p.getGeneratedKeys()){if(!keys.next())throw new SQLException("Impossible de créer la vente.");idVente=keys.getInt(1);}
                }
                try(PreparedStatement p=con.prepareStatement("INSERT INTO detail_vente(id_vente,id_produit,quantite,prix_unitaire) VALUES(?,?,?,?)")){
                    p.setInt(1,idVente);p.setInt(2,idProduit);p.setInt(3,quantite);p.setDouble(4,prixUnitaire);p.executeUpdate();
                }
                try(PreparedStatement p=con.prepareStatement("UPDATE produit SET stock=stock-? WHERE id_produit=? AND stock>=?")){
                    p.setInt(1,quantite);p.setInt(2,idProduit);p.setInt(3,quantite);if(p.executeUpdate()!=1)throw new SQLException("Le stock a changé ; la vente a été annulée. Réessayez.");
                }
                con.commit();
            } catch(Exception ex) { con.rollback();throw ex; }
        } catch(Exception ex) {JOptionPane.showMessageDialog(this,"Vente non enregistrée : "+ex.getMessage(),"Vente",JOptionPane.ERROR_MESSAGE);return;}
        JOptionPane.showMessageDialog(this,"Vente enregistrée.");chargerTableVentes();txtQuantiteVente.setText("");txtPrixVente.setText("");
        FacturePDF.generer(idVente);
    }//GEN-LAST:event_btnVendreActionPerformed

