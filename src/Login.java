    private void btnConnectionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConnectionActionPerformed
        // TODO add your handling code here:
        //on recupere ce que utilisateur a tape
        String nom = txtNom.getText().trim();
        char[] motDePasse = txtMotDePasse.getPassword();
        //2. verification simple
        if(nom.isEmpty() || motDePasse.length == 0){
        javax.swing.JOptionPane.showMessageDialog(this, "Remplis tous les champs !");
        return;
    }
        //on cherche dans la base gestion_comerce
        try (java.sql.Connection con = ConnexionBD.getConnection()) {
            if (con == null) throw new java.sql.SQLException("Connexion à la base indisponible.");
            try (java.sql.PreparedStatement pst = con.prepareStatement(
                    "SELECT id_utilisateur, nom_utilisateur, mot_de_passe, profil FROM utilisateur WHERE nom_utilisateur=?")) {
                pst.setString(1, nom);
                try (java.sql.ResultSet rs = pst.executeQuery()) {
                    if (!rs.next()) {
                        javax.swing.JOptionPane.showMessageDialog(this,"Nom d'utilisateur ou mot de passe incorrect.");
                        return;
                    }
                    String stocke = rs.getString("mot_de_passe");
                    boolean valide = MotDePasseUtil.estHache(stocke)
                            ? MotDePasseUtil.verifier(motDePasse, stocke)
                            : java.security.MessageDigest.isEqual(new String(motDePasse).getBytes(java.nio.charset.StandardCharsets.UTF_8),
                                    (stocke == null ? "" : stocke).getBytes(java.nio.charset.StandardCharsets.UTF_8));
                    if (!valide) {
                        javax.swing.JOptionPane.showMessageDialog(this,"Nom d'utilisateur ou mot de passe incorrect.");
                        return;
                    }
                    int id = rs.getInt("id_utilisateur");
                    String profil = rs.getString("profil");
                    String nomEnregistre = rs.getString("nom_utilisateur");
                    if (!MotDePasseUtil.estHache(stocke)) {
                        try (java.sql.PreparedStatement maj = con.prepareStatement("UPDATE utilisateur SET mot_de_passe=? WHERE id_utilisateur=?")) {
                            maj.setString(1, MotDePasseUtil.hacher(motDePasse)); maj.setInt(2, id); maj.executeUpdate();
                        }
                    }
                    SessionUtilisateur.ouvrir(id, nomEnregistre, profil);
                    new MenuPrincipal().setVisible(true);
                    this.dispose();
                }
            }
        } catch (Exception e){
            javax.swing.JOptionPane.showMessageDialog(this,"Erreur: " + e.getMessage());
        } finally {
            java.util.Arrays.fill(motDePasse, '\0');
            txtMotDePasse.setText("");
        }
    }//GEN-LAST:event_btnConnectionActionPerformed

