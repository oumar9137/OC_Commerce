 PreparedStatement pst = con.prepareStatement(sql);
 pst.setString(1, txtDesignation.getText());
 pst.setInt(2, idCat);
 pst.setDouble(3, Double.parseDouble(txtPrixAchat.getText()));
 pst.setDouble(4, Double.parseDouble(txtPrixVente.getText()));
 pst.setInt(5, Integer.parseInt(txtStock.getText()));
