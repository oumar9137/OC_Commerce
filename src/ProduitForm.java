    private void btnSupprimerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSupprimerActionPerformed
        // TODO add your handling code here:
        
 
 int ligne = tableProduit.getSelectedRow();
 if(ligne == -1){
 JOptionPane.showMessageDialog(this, "Sélectionne un produit d'abord!");
 return;
 }
 int id = Integer.parseInt(tableProduit.getValueAt(ligne, 0).toString());
 
 // Vérifier si le produit est déjà utilisé
 try{
 Connection con = ConnexionBD.getConnection();
 String check = "SELECT COUNT(*) FROM detail_achat WHERE id_produit = ?";
 PreparedStatement pstCheck = con.prepareStatement(check);
 pstCheck.setInt(1, id);
 ResultSet rs = pstCheck.executeQuery();
 if(rs.next() && rs.getInt(1) > 0){
 JOptionPane.showMessageDialog(this, 
 "IMPOSSIBLE de supprimer !\nCe produit a déjà des achats.\nMets son stock à 0 si tu ne veux plus l'utiliser.");
 return;
 }
 
 int rep = JOptionPane.showConfirmDialog(this, "Vraiment supprimer ?",
"Confirmation", JOptionPane.YES_NO_OPTION);
 if(rep == JOptionPane.YES_OPTION){
 String sql = "DELETE FROM produit WHERE id_produit = ?";
 PreparedStatement pst = con.prepareStatement(sql);
 pst.setInt(1, id);
 pst.executeUpdate();
 JOptionPane.showMessageDialog(this, "Supprimé!");
 chargerProduits(); // ta méthode qui remplit la table
 btnAnnulerActionPerformed(null);
 }
 }catch(Exception e){
 JOptionPane.showMessageDialog(this, "Erreur: "+e.getMessage());
 }

    }//GEN-LAST:event_btnSupprimerActionPerformed

