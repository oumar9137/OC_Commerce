 // Remplir le Combo avec libelle_categorie
 void chargerCategories(){
 try {
 comboCategorie.removeAllItems();
 Statement st = con.createStatement();
 ResultSet rs = st.executeQuery("SELECT libelle_categorie FROM categorie");
 while(rs.next()){
 comboCategorie.addItem(rs.getString("libelle_categorie"));
 }
 } catch(Exception e){ e.printStackTrace(); }
 }
 
 // Remplir la JTable
 void chargerProduits(){
 try {
 DefaultTableModel model = (DefaultTableModel) tableProduit.getModel();
 model.setRowCount(0);
 String sql = "SELECT p.id_produit, p.designation, c.libelle_categorie, p.prix_achat, p.prix_vente, p.stock, p.seuil_minimal FROM produit p JOIN categorie c ON p.id_categorie = c.id_categorie";
 Statement st = con.createStatement();
 ResultSet rs = st.executeQuery(sql);
 while(rs.next()){
 model.addRow(new Object[]{ rs.getInt(1), rs.getString(2), rs.getString(3), rs.getDouble(4), rs.getInt(5), rs.getInt(6), rs.getInt(7)});
 }
 } catch(Exception e){ e.printStackTrace(); }
 }
