   public void chargerStatistiques(){
 try{
 Connection con = ConnexionBD.getConnection();
 
 // 1. CA Total depuis detail_vente
 ResultSet rs = con.createStatement().executeQuery("SELECT IFNULL(SUM(quantite * prix_unitaire),0) FROM detail_vente");
 int totalVente = 0;
 if(rs.next()){
 totalVente = rs.getInt(1);
 lblCA.setText("CA Total: " + totalVente + " FCFA");
 }
 
 // 2. Total Achats depuis detail_achat
 rs = con.createStatement().executeQuery("SELECT IFNULL(SUM(quantite * prix_achat),0) FROM detail_achat");
 int totalAchat = 0;
 if(rs.next()) totalAchat = rs.getInt(1);
 
 // 3. Bénéfice
 lblBenefice.setText("Bénéfice: " + (totalVente - totalAchat) + " FCFA");
 
 // 4. Nombre de produits
 rs = con.createStatement().executeQuery("SELECT COUNT(*) FROM produit");
 if(rs.next()) lblNbProduits.setText("Produits: " + rs.getInt(1));
 
 // 5. Nombre de ventes
 rs = con.createStatement().executeQuery("SELECT COUNT(*) FROM vente");
 int nbVentes = 0;
 if(rs.next()) nbVentes = rs.getInt(1);
 
 // 6. Table Alerte stock < 20
 PreparedStatement pst = con.prepareStatement("SELECT designation, stock FROM produit WHERE stock < 10 ORDER BY stock ASC");
 ResultSet rs2 = pst.executeQuery();
 javax.swing.table.DefaultTableModel model =
(javax.swing.table.DefaultTableModel) tableAlerte.getModel();
 model.setRowCount(0);
 int c = 0;
 while(rs2.next()){
 model.addRow(new Object[]{rs2.getString(1), rs2.getInt(2)});
 c++;
 }
 lblAlerte.setText("Alertes: " + c + " produits / Ventes: " + nbVentes);
 
 }catch(Exception e){
 javax.swing.JOptionPane.showMessageDialog(this, e.getMessage());
 }
}
