    private void btnModifierActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModifierActionPerformed
        // TODO add your handling code here:
        try{
 int ligne = tableClient.getSelectedRow();
 int id = Integer.parseInt(tableClient.getValueAt(ligne, 0).toString());
 
 Connection con = ConnexionBD.getConnection();
 String sql = "UPDATE client SET nom=?, prenom=?, telephone=?, adresse=? WHERE id_client=?";
 PreparedStatement pst = con.prepareStatement(sql);
 pst.setString(1, txtNom.getText());
 pst.setString(2, txtPrenom.getText());
 pst.setString(3, txtTel.getText());
 pst.setString(4, txtAdresse.getText());
 pst.setInt(5, id);
 pst.executeUpdate();
 
 chargerClients();
 JOptionPane.showMessageDialog(this, "Modifié !");
}catch(Exception e){ JOptionPane.showMessageDialog(this, e.getMessage());
 }

    }//GEN-LAST:event_btnModifierActionPerformed

    private void btnSupprimerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSupprimerActionPerformed
        // TODO add your handling code here:
        try{
 int ligne = tableClient.getSelectedRow();
 int id = Integer.parseInt(tableClient.getValueAt(ligne, 0).toString());
 
 Connection con = ConnexionBD.getConnection();
 String sql = "DELETE FROM client WHERE id_client=?";
 PreparedStatement pst = con.prepareStatement(sql);
 pst.setInt(1, id);
 pst.executeUpdate();
 
 chargerClients();
 JOptionPane.showMessageDialog(this, "Supprimé !");
}catch(Exception e){ JOptionPane.showMessageDialog(this, e.getMessage()); 
}
    }//GEN-LAST:event_btnSupprimerActionPerformed

