    private void btnEnregistreActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEnregistreActionPerformed
        // TODO add your handling code here:
      try {
 Connection con = ConnexionBD.getConnection();
 String sql = "INSERT INTO client(nom, prenom, telephone, adresse) VALUES(?,?,?,?)";
 PreparedStatement pst = con.prepareStatement(sql);
 pst.setString(1, txtNom.getText());
 pst.setString(2, txtPrenom.getText());
 pst.setString(3, txtTel.getText());
 pst.setString(4, txtAdresse.getText());
 pst.executeUpdate();
 
 chargerClients();
 
 JOptionPane.showMessageDialog(this, "Client enregistré !");
 
 // vide les champs
 txtNom.setText("");
 txtPrenom.setText("");
 txtTel.setText("");
 txtAdresse.setText("");
 
} catch(Exception e){
 JOptionPane.showMessageDialog(this, "Erreur: " + e.getMessage());
}  
    }//GEN-LAST:event_btnEnregistreActionPerformed

