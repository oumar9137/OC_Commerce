    public void chargerClients(){
 try{
 javax.swing.table.DefaultTableModel model =
(javax.swing.table.DefaultTableModel) tableClient.getModel();
 model.setRowCount(0);
 model.setColumnIdentifiers(new Object[]{"ID", "Nom", "Prenom", "Tel",
"Adresse"});
 
 Connection con = ConnexionBD.getConnection();
 ResultSet rs = con.createStatement().executeQuery("SELECT * FROM client");
 while(rs.next()){
 model.addRow(new Object[]{
 rs.getInt("id_client"),
 rs.getString("nom"),
 rs.getString("prenom"),
 rs.getString("telephone"),
 rs.getString("adresse")
    });
   }
   }catch(Exception e){ e.printStackTrace(); }
  }

